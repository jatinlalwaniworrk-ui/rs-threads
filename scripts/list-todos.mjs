// Writes TODO.md: every yellow [TODO] on the built site grouped by page, every photo still needed,
// and every placeholder left in the data files. Run with `npm run todos` (it builds the site first).

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const decode = (s) =>
  s.replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');

function htmlFiles(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return htmlFiles(p);
    return p.endsWith('.html') ? [p] : [];
  });
}

// Each line of the page that has a [TODO], with the TODOs in backticks, e.g. "GSTIN: `[TODO]`".
// When a TODO sits alone (a value cell), the label on the line before is added.
function todosIn(html) {
  const body = html.replace(/<head>[\s\S]*?<\/head>/, '').replace(/<template[\s\S]*?<\/template>/g, '');
  const lines = body
    .replace(/<mark class="todo">([\s\S]*?)<\/mark>/g, '\u0001$1\u0002')
    .replace(/<\/(p|li|h1|h2|h3|dt|dd|div|section|legend|label|button|form)>|<(dl|ul|ol|dt|dd)\b[^>]*>|<br\s*\/?>/g, '\n')
    .replace(/<[^>]+>/g, '')
    .split('\n')
    .map((l) => decode(l).replace(/\s+/g, ' ').trim())
    .filter(Boolean);
  const found = [];
  lines.forEach((text, i) => {
    const first = text.indexOf('\u0001');
    if (first === -1) return;
    const last = text.lastIndexOf('\u0002');
    let before = text.slice(0, first).trim();
    if (before.length > 60) before = `…${before.slice(-60).trimStart()}`;
    if (!before && i > 0 && !lines[i - 1].includes('\u0001') && lines[i - 1].length < 50) before = `${lines[i - 1]}:`;
    const marks = text.slice(first, last + 1).replace(/\u0001/g, '`').replace(/\u0002/g, '`');
    found.push([before, marks].filter(Boolean).join(' '));
  });
  return found;
}

const photosIn = (html) => [...html.matchAll(/data-photo-needed="([^"]+)"/g)].map((m) => decode(m[1]));

const pages = htmlFiles(dist).map((file) => {
  const html = readFileSync(file, 'utf8');
  const path = `/${relative(dist, file).replace(/\.html$/, '').replace(/^index$/, '')}`;
  const footerAt = html.indexOf('<footer');
  const headerEnd = html.indexOf('</header>');
  const h1 = decode(html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1].replace(/<[^>]+>/g, '') ?? path);
  return {
    path,
    h1,
    global: [...new Set(todosIn(html.slice(0, headerEnd) + html.slice(footerAt)))],
    todos: [...new Set(todosIn(html.slice(headerEnd, footerAt)))],
    photos: photosIn(html),
  };
});

const order = ['/', '/products', '/shade-card', '/become-a-dealer', '/find-a-dealer', '/genuine', '/about', '/contact',
  '/downloads', '/privacy', '/terms-of-use', '/terms-of-trade', '/404'];
const rank = (p) => (order.includes(p) ? order.indexOf(p) : p.startsWith('/products/') ? 1.5 : 99);
pages.sort((a, b) => rank(a.path) - rank(b.path) || a.path.localeCompare(b.path));

// TODOs on every product page are listed once.
const productPages = pages.filter((p) => p.path.startsWith('/products/'));
const sharedProduct = productPages.length
  ? productPages[0].todos.filter((t) => productPages.every((p) => p.todos.includes(t)))
  : [];

const out = [];
const line = (s = '') => out.push(s);

line('# TODO');
line();
line(`Generated by \`npm run todos\` on ${new Date().toISOString().slice(0, 10)}. Every yellow [TODO] on the site is listed below, by page.`);
line('Most values live in `src/data/site.json` (see README.md). Fix them, then run `npm run todos` again to refresh this file.');
line();
line('## Before launch');
line();
line('- **WhatsApp number** (`whatsapp` in site.json). Until it is set, every WhatsApp button and the enquiry list go to the 404 page.');
line('- **GSTIN, address, phone and business hours.** Shown in the footer of every page and checked by buyers before they call.');
line('- **Domain** (`domain` in site.json). Until it is set, the sitemap and share links use the Netlify address.');
line('- **Netlify form notifications.** In Netlify: Forms, then turn on email notifications for the `enquiry` and `dealer` forms.');
line('- **Google Sheet.** Deploy `scripts/google-apps-script.gs` as a web app (steps in README.md) and put its URL in `leads.appsScriptUrl`.');
line('- **Legal review** of Privacy policy, Terms of use and Terms of trade, then remove the "Draft" note (see README.md).');
line();

const section = (title, items) => {
  if (!items.length) return;
  line(`## ${title}`);
  line();
  for (const item of items) line(`- ${item}`);
  line();
};

section('Every page (header and footer)', pages[0]?.global ?? []);
section('Every product page', sharedProduct);
for (const p of pages) {
  const own = p.path.startsWith('/products/') ? p.todos.filter((t) => !sharedProduct.includes(t)) : p.todos;
  section(`${p.h1} (\`${p.path}\`)`, own);
}

line('## Photos needed');
line();
line('Put compressed WebP photos in `public/images/` and replace the placeholder blocks. Never use stock photos of thread.');
line();
const seenPhotos = new Set();
for (const p of pages) {
  const photos = p.photos.filter((x) => !seenPhotos.has(x));
  photos.forEach((x) => seenPhotos.add(x));
  if (photos.length) line(`- \`${p.path}\`: ${photos.join('; ')}`);
}
line();

// Placeholders in the data files.
const site = read('src/data/site.json');
const flat = (obj, prefix = '') =>
  Object.entries(obj).flatMap(([k, v]) =>
    typeof v === 'object' && v !== null ? flat(v, `${prefix}${k}.`) : [[`${prefix}${k}`, v]],
  );
const isTodo = (v) => typeof v === 'string' && v.includes('[TODO');
const products = read('src/data/products.json');
const shades = read('src/data/shades.json');
const placeholderShades = shades.filter((s) => s.placeholder).length;
const downloads = ['company-profile', 'product-catalogue', 'shade-card'].filter(
  (f) => !existsSync(join(root, 'public', 'downloads', `${f}.pdf`)),
);

line('## Data files');
line();
line('`src/data/site.json`:');
line();
for (const [key, value] of flat(site).filter(([, v]) => isTodo(v))) line(`- \`${key}\`: ${value}`);
line();
line('`src/data/products.json`:');
line();
for (const p of products) {
  for (const [key, value] of Object.entries(p).filter(([, v]) => isTodo(v))) line(`- ${p.name}, \`${key}\`: ${value}`);
}
line('- Every product: denier, ply, colourfastness and recommended machine speed (shown as [TODO: confirm] on product pages).');
line();
line('Other data:');
line();
if (placeholderShades) line(`- \`shades.json\`: ${placeholderShades} placeholder shades (P01 to P24). Replace with the real shade card.`);
if (!read('src/data/dealers.json').length) line('- `dealers.json`: no dealers yet. Find a dealer shows the "building our network" message until you add one.');
if (!read('src/data/testimonials.json').length) line('- `testimonials.json`: empty. Add only with the customer\'s written permission.');
for (const f of downloads) line(`- \`public/downloads/${f}.pdf\`: not uploaded. Its button goes to the 404 page.`);
line();

line('## Not on the site yet');
line();
line('- Switch the email to sales@[domain] once the domain mailbox exists (`email` in site.json).');
line('- Horizontal logo file. The header uses one cut from the stacked logo (`scripts/make-logos.py`). An original vector file (SVG, AI, EPS or PDF) would be sharper.');
line('- Hindi pages under /hi/. "हिंदी" in the header goes to the 404 page until then (see README.md).');
line('- Meta Pixel: off. Set `analytics.metaPixel` and `analytics.metaPixelEnabled`, and update the privacy policy first.');
line('- Consent box: ticking it is required to send a form. Ask the lawyer whether marketing consent should be a separate, optional box.');
line();

writeFileSync(join(root, 'TODO.md'), out.join('\n'));
console.log(`TODO.md written: ${out.filter((l) => l.startsWith('- ')).length} items.`);
